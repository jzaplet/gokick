// checkUsage is the union deadness gate: every catalog key must be referenced
// either in Go production code (a msgkey.<Const> selector under app/ + cmd/,
// tests and the generated file excluded) or in frontend source (a quoted
// 'the.key' literal anywhere under assets/, the generated catalogs excluded).
// A key dead on BOTH sides is a text nobody can ever see.
func checkUsage(root string, canonical map[string]message, scan *productionScan) []string {
	if len(scan.usedNames) == 0 {
		return []string{"no msgkey usages found in Go production code — the scan is broken"}
	}
	feLiterals, scanned, err := frontendKeyLiterals(root)
	if err != nil {
		return []string{err.Error()}
	}
	if scanned == 0 {
		return []string{"no frontend source files scanned under assets/ — the scan is broken"}
	}

	var problems []string
	for _, key := range slices.Sorted(maps.Keys(canonical)) {
		if scan.usedNames[constName(key)] || feLiterals[key] {
			continue
		}
		problems = append(problems, fmt.Sprintf(
			"key %q is referenced neither by Go production code (msgkey.%s) nor by "+
				"frontend source — dead catalog entry", key, constName(key)))
	}
	return problems
}

// feKeyLiteralRe matches a quote-delimited token in catalog-key shape —
// 'user.created', "user.created", `user.created` — the only form a key
// reference takes in frontend source. Constraining the CONTENT to the key
// charset (rather than "anything between two quotes") is what makes the scan
// survive nesting: in :aria-label="t('nav.close_menu')" the outer pair holds
// no key and the inner one is still found.
var feKeyLiteralRe = regexp.MustCompile("['\"`]([a-z0-9._]+)['\"`]")

// frontendKeyLiterals collects the quoted key-shaped literals of every
// frontend source file under assets/ (.ts/.tsx/.vue/.js) into one set and
// reports how many files it saw. The generated catalog dir is skipped — it
// quotes every key, so scanning it would make the deadness gate blind. One
// pass answering each key with a set lookup replaces a per-key scan of the
// whole tree; a bare word in prose no longer counts as a reference.
func frontendKeyLiterals(root string) (map[string]bool, int, error) {
	literals := map[string]bool{}
	scanned := 0
	generated := filepath.Join(root, filepath.FromSlash(tsOutDir))
	err := filepath.WalkDir(filepath.Join(root, "assets"), func(
		path string, d fs.DirEntry, err error,
	) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path == generated {
				return fs.SkipDir
			}
			return nil
		}
		switch filepath.Ext(path) {
		case ".ts", ".tsx", ".vue", ".js":
		default:
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		scanned++
		for _, match := range feKeyLiteralRe.FindAllSubmatch(data, -1) {
			literals[string(match[1])] = true
		}
		return nil
	})
	if err != nil {
		return nil, 0, fmt.Errorf("walk assets: %w", err)
	}
	return literals, scanned, nil
}

// productionScan is what ONE pass over the production Go tree yields: the
// msgkey constants the code references (the Go half of the deadness gate) and
// every keyed call site (the params gate). Both gates used to walk and parse
// the whole app/ + cmd/ tree on their own.
type productionScan struct {
	usedNames map[string]bool
	sites     []keyedCallSite
}

// scanProductionGo parses every production Go file under app/ + cmd/ once
// (_test.go and the generated keys file excluded) and runs both gates'
// visitors over it. Files are prefiltered with an ImportsOnly parse: neither
// gate can see anything in a file that does not import msgkey, so only the
// handful that do pay for a full parse.
func scanProductionGo(root string) (*productionScan, error) {
	scan := &productionScan{usedNames: map[string]bool{}}
	fset := token.NewFileSet()
	prefilter := token.NewFileSet() // imports only — keeps the position-carrying fset clean
	for _, sub := range []string{"app", "cmd"} {
		err := filepath.WalkDir(filepath.Join(root, sub), func(
			path string, d fs.DirEntry, err error,
		) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				return nil
			}
			if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") ||
				strings.HasSuffix(path, "keys.gen.go") {
				return nil
			}
			src, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			local, err := msgkeyImportName(prefilter, path, src)
			if err != nil || local == "" {
				return err
			}
			f, parseErr := parser.ParseFile(fset, path, src, 0)
			if parseErr != nil {
				return fmt.Errorf("parse %s: %w", path, parseErr)
			}
			if err := scan.collect(fset, f, local); err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	return scan, nil
}

// msgkeyImportName returns the name msgkey is imported under in src, or "" when
// the file does not import it at all.
func msgkeyImportName(fset *token.FileSet, path string, src []byte) (string, error) {
	f, err := parser.ParseFile(fset, path, src, parser.ImportsOnly)
	if err != nil {
		return "", fmt.Errorf("parse imports of %s: %w", path, err)
	}
	for _, imp := range f.Imports {
		importPath, uerr := strconv.Unquote(imp.Path.Value)
		if uerr != nil {
			return "", fmt.Errorf("%s: malformed import path %s: %w", path, imp.Path.Value, uerr)
		}
		if importPath != msgkeyImportPath {
			continue
		}
		if imp.Name != nil {
			return imp.Name.Name, nil
		}
		return "msgkey", nil
	}
	return "", nil
}

// collect runs both gates' visitors over one parsed file; local is the name
// msgkey is imported under there.
func (s *productionScan) collect(fset *token.FileSet, f *ast.File, local string) error {
	var visitErr error
	ast.Inspect(f, func(n ast.Node) bool {
		switch node := n.(type) {
		case *ast.SelectorExpr:
			if ident, isIdent := node.X.(*ast.Ident); isIdent && ident.Name == local {
				s.usedNames[node.Sel.Name] = true
			}
		case *ast.CompositeLit:
			site, err := keyedSite(fset, node, local)
			switch {
			case err != nil && visitErr == nil:
				visitErr = err
			case site != nil:
				s.sites = append(s.sites, *site)
			}
		}
		return true
	})
	return visitErr
}

// literalParamNames extracts the constant string keys of a `map[string]any{...}`
// literal. literal=false means the expression is not such a literal (a variable,
// a call, a non-string key) and the call site cannot be checked statically; an
// error means a key that will not unquote, i.e. malformed source.
func literalParamNames(expr ast.Expr) (names map[string]bool, literal bool, err error) {
	lit, isLit := expr.(*ast.CompositeLit)
	if !isLit {
		return nil, false, nil
	}
	if _, isMap := lit.Type.(*ast.MapType); !isMap {
		return nil, false, nil
	}
	names = map[string]bool{}
	for _, elt := range lit.Elts {
		kv, isKV := elt.(*ast.KeyValueExpr)
		if !isKV {
			return nil, false, nil
		}
		key, isStr := kv.Key.(*ast.BasicLit)
		if !isStr || key.Kind != token.STRING {
			return nil, false, nil
		}
		name, uerr := strconv.Unquote(key.Value)
		if uerr != nil {
			return nil, false, fmt.Errorf("malformed Params key %s: %w", key.Value, uerr)
		}
		names[name] = true
	}
	return names, true, nil
}

// keyedCallSite is one composite literal carrying `Key: msgkey.<Const>` —
// the shape every keyed error/config literal in production uses.
type keyedCallSite struct {
	pos       token.Position
	constName string
	params    map[string]bool
	checkable bool // false: Params is a non-literal expression
}

// keyedSite reads one composite literal as a keyed call site: a `Key:` field
// holding a msgkey selector, plus the statically known Params. nil means the
// literal is not one (no such Key field).
func keyedSite(
	fset *token.FileSet,
	lit *ast.CompositeLit,
	local string,
) (*keyedCallSite, error) {
	site := keyedCallSite{params: map[string]bool{}, checkable: true}
	for _, elt := range lit.Elts {
		kv, isKV := elt.(*ast.KeyValueExpr)
		if !isKV {
			continue
		}
		field, isIdent := kv.Key.(*ast.Ident)
		if !isIdent {
			continue
		}
		switch field.Name {
		case "Key":
			sel, isSel := kv.Value.(*ast.SelectorExpr)
			if !isSel {
				continue
			}
			if ident, ok := sel.X.(*ast.Ident); ok && ident.Name == local {
				site.constName = sel.Sel.Name
				site.pos = fset.Position(lit.Pos())
			}
		case "Params":
			names, literal, err := literalParamNames(kv.Value)
			if err != nil {
				return nil, err
			}
			if !literal {
				site.checkable = false
				continue
			}
			site.params = names
		}
	}
	if site.constName == "" {
		return nil, nil
	}
	return &site, nil
}

// checkCallSiteParams closes the loop the catalog validation cannot: the
// catalog knows its placeholders, but a Go call site that forgets (or
// misnames) a Params entry ships a message the frontend cannot interpolate.
// Every statically checkable `Key: msgkey.X` literal must cover every {param}
// (incl. count, which drives plural selection) of X's canonical message.
// Params passed as a non-literal expression are skipped — they cannot be
// verified statically.
func checkCallSiteParams(canonical map[string]message, scan *productionScan) []string {
	keysByConst := map[string]string{}
	for key := range canonical {
		keysByConst[constName(key)] = key
	}

	var problems []string
	checked := 0
	for _, site := range scan.sites {
		if !site.checkable {
			continue
		}
		key, known := keysByConst[site.constName]
		if !known {
			// A selector like msgkey.Key (the type) — not a message constant.
			continue
		}
		checked++
		for _, name := range canonical[key].params() {
			if !site.params[name] {
				problems = append(problems, fmt.Sprintf(
					"%s: msgkey.%s (%q) is missing template param %q — "+
						"the frontend cannot fill the placeholder",
					site.pos, site.constName, key, name))
			}
		}
	}
	if checked == 0 {
		problems = append(problems,
			"no checkable msgkey call sites found in Go production code — the gate sees nothing")
	}
	return problems
}

// feCallSiteRe matches a t() call with a literal key and, optionally, a flat
// literal params object: t('bulk.selected', { count, total }). RE2 has no
// lookbehind, so the leading non-word guard is what keeps `format(` and a
// `.t(` method call out. A negated class spans newlines, so a params object
// broken across lines still matches.
var feCallSiteRe = regexp.MustCompile(
	"(?:^|[^\\w.$])t\\(\\s*['\"`]([a-z0-9._]+)['\"`]\\s*(?:,\\s*\\{([^{}]*)\\}\\s*)?\\)")

// feParamNameRe: one entry of a literal params object, in `name:` or shorthand
// `name` form.
var feParamNameRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// literalFEParams reads a flat `{ a, b: expr }` params body into a name set.
// ok=false means an entry is not a plain `name` / `name:` pair — a spread, a
// computed key, or a value carrying a comma — and the call site is then
// SKIPPED rather than guessed at, exactly like a non-literal Go Params.
func literalFEParams(body string) (map[string]bool, bool) {
	names := map[string]bool{}
	for _, part := range strings.Split(body, ",") {
		entry := strings.TrimSpace(part)
		if entry == "" {
			continue
		}
		if i := strings.IndexByte(entry, ':'); i >= 0 {
			entry = strings.TrimSpace(entry[:i])
		}
		if !feParamNameRe.MatchString(entry) {
			return nil, false
		}
		names[entry] = true
	}
	return names, true
}

// checkFrontendCallSiteParams is checkCallSiteParams' frontend half. The Go
// scan only walks app/ + cmd/, but most placeholder-bearing keys are rendered
// ONLY from assets/, where TranslationParams is a flat Record<string, …> that
// cannot tell one key's params from another's — so vue-tsc happily accepts
// t('bulk.selected', { count }) for a message that also needs {total}, and
// interpolate leaves the literal "{total}" on screen. Every t() call with a
// statically readable params object must cover its key's placeholders.
func checkFrontendCallSiteParams(root string, canonical map[string]message) []string {
	var problems []string
	checked := 0
	generated := filepath.Join(root, filepath.FromSlash(tsOutDir))
	err := filepath.WalkDir(filepath.Join(root, "assets"), func(
		path string, d fs.DirEntry, err error,
	) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path == generated {
				return fs.SkipDir
			}
			return nil
		}
		switch filepath.Ext(path) {
		case ".ts", ".tsx", ".vue", ".js":
		default:
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			rel = path
		}
		for _, match := range feCallSiteRe.FindAllSubmatch(data, -1) {
			key := string(match[1])
			msg, known := canonical[key]
			if !known {
				// Not a catalog key (a route name, a CSS token) — the deadness
				// gate owns unknown-looking literals, not this one.
				continue
			}
			supplied, literal := literalFEParams(string(match[2]))
			if !literal {
				continue
			}
			checked++
			for _, name := range msg.params() {
				if !supplied[name] {
					problems = append(problems, fmt.Sprintf(
						"%s: t(%q) is missing template param %q — "+
							"the placeholder would render literally",
						rel, key, name))
				}
			}
		}
		return nil
	})
	if err != nil {
		return []string{fmt.Sprintf("walk assets: %v", err)}
	}
	if checked == 0 {
		return append(problems,
			"no checkable t() call sites found under assets/ — the gate sees nothing")
	}
	return problems
}

// langConstName maps a catalog's language token to its Go constant name —
// LangCS, LangEN. Language tags are lowercase by langTokenRe, and Go style
// uppercases short codes wholesale (the same shape the hand-written constants
// had before they became generated, so no call site moved).
func langConstName(lang string) string { return "Lang" + strings.ToUpper(lang) }

// renderLangsGo emits the backend's declaration of the language set: one Lang
// constant per discovered catalog, the canonical default, and the two lookups
// every consumer goes through. Nothing here is language-specific knowledge —
// it is the catalog filenames transcribed into Go, which is precisely why it
// must not be hand-maintained.
func renderLangsGo(langs []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(genHeader + "\n\n")
	b.WriteString("package shared\n\n")
	b.WriteString("// The UI languages the app ships catalogs for, discovered from the\n")
	b.WriteString("// locale/messages.<lang>.json filenames. Adding a language is\n")
	b.WriteString("// a catalog file plus `make i18n-gen` — never an edit here.\n")
	b.WriteString("const (\n")
	for _, lang := range langs {
		fmt.Fprintf(&b, "\t%s Lang = %q\n", langConstName(lang), lang)
	}
	b.WriteString("\n")
	b.WriteString("\t// DefaultLang is the canonical language: the fallback when a request\n")
	b.WriteString("\t// carries no usable language signal, and the one served at bare URLs.\n")
	b.WriteString("\t// Mirrors CANONICAL_LANG on the frontend.\n")
	fmt.Fprintf(&b, "\tDefaultLang = %s\n", langConstName(canonicalLang))
	b.WriteString(")\n\n")

	b.WriteString("// SupportedLangs lists every language the app ships catalogs for.\n")
	b.WriteString("func SupportedLangs() []Lang { return []Lang{")
	for i, lang := range langs {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(langConstName(lang))
	}
	b.WriteString("} }\n\n")

	b.WriteString("// ParseLang validates a raw value (header, URL segment, DB column) into a\n")
	b.WriteString("// Lang. Matching is exact — normalization (e.g. \"cs-CZ\", \"EN\") is the\n")
	b.WriteString("// caller's job; HTTP Accept-Language negotiation lives in the\n")
	b.WriteString("// LangMiddleware.\n")
	b.WriteString("func ParseLang(raw string) (Lang, bool) {\n")
	b.WriteString("\tswitch Lang(raw) {\n")
	for _, lang := range langs {
		name := langConstName(lang)
		fmt.Fprintf(&b, "\tcase %s:\n\t\treturn %s, true\n", name, name)
	}
	b.WriteString("\t}\n\n\treturn \"\", false\n}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated source: %w", err)
	}

	return src, nil
}

// renderLangsTS emits the frontend's declaration of the same set. The Lang
// union is declared HERE rather than in hand-written lang.ts so the two cannot
// drift: lang.ts re-exports it, and every consumer keeps importing from
// lang.ts as before.
func renderLangsTS(langs []string) []byte {
	var b strings.Builder
	b.WriteString(tsGenHeader)
	b.WriteString("// The UI languages the app ships catalogs for, discovered from the\n")
	b.WriteString("// locale/messages.<lang>.json filenames. Mirrors shared.SupportedLangs.\n")
	b.WriteString("export const SUPPORTED_LANGS = [")
	for i, lang := range langs {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "'%s'", lang)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type Lang = (typeof SUPPORTED_LANGS)[number];\n\n")
	b.WriteString("// CANONICAL_LANG lives at bare URLs; every other language carries a\n")
	b.WriteString("// /<lang> path prefix. Mirrors shared.DefaultLang.\n")
	fmt.Fprintf(&b, "export const CANONICAL_LANG: Lang = '%s';\n", canonicalLang)

	return []byte(b.String())
}

// renderCatalogsTS emits the language→catalog record the renderer looks up in.
// The `satisfies` is the frontend half of catalog validation — a malformed
// plural or a key missing from a non-canonical catalog fails vue-tsc here —
// and it only covers every language because the record is generated from the
// same discovered set as the Lang union it is checked against.
func renderCatalogsTS(langs []string) []byte {
	var b strings.Builder
	b.WriteString(tsGenHeader)
	for _, lang := range langs {
		fmt.Fprintf(&b, "import { %sCatalog } from '%s/%s';\n", lang, feCatalogModule, lang)
	}
	fmt.Fprintf(&b, "import type { Lang, TranslationCatalog } from '%s';\n\n", feLangModule)
	b.WriteString("export const catalogs = {\n")
	for _, lang := range langs {
		fmt.Fprintf(&b, "    %s: %sCatalog,\n", lang, lang)
	}
	b.WriteString("} satisfies Record<Lang, TranslationCatalog>;\n\n")
	b.WriteString("// The canonical catalog under a language-neutral name: it is complete by\n")
	b.WriteString("// construction, so the TranslationKey union derives from it and membership\n")
	b.WriteString("// in it IS the definition of a known key. Exported from here so no\n")
	b.WriteString("// hand-written module has to name the canonical language.\n")
	fmt.Fprintf(&b, "export const canonicalCatalog = %sCatalog;\n", canonicalLang)

	return []byte(b.String())
}

// cldrPluralJS asks Node for the plural categories of each language named on
// the command line. resolvedOptions().locale is compared back against the
// request because Intl FALLS BACK for a tag its ICU does not know — without
// the comparison an unknown language would quietly inherit the default
// locale's categories, which is worse than having no entry at all.
const cldrPluralJS = `const out = {};
for (const lang of process.argv.slice(1)) {
    const opts = new Intl.PluralRules(lang).resolvedOptions();
    if (opts.locale.toLowerCase().split('-')[0] !== lang) {
        process.stderr.write(lang + ' -> ' + opts.locale);
        process.exit(2);
    }
    out[lang] = opts.pluralCategories.slice().sort();
}
process.stdout.write(JSON.stringify(out));`

// cldrPluralForms reads the categories out of Node's Intl.PluralRules — the
// same implementation the renderer selects forms with at runtime, so the gate
// cannot demand a form the frontend would never pick (or miss one it does).
// One spawn per run, on both `generate` and `check`: `make lint` already
// requires Node for eslint, vue-tsc and knip, and a cached table would ratify
// its own errors (see the pluralForms doc).
func cldrPluralForms(langs []string) (pluralForms, error) {
	cmd := exec.Command("node", append([]string{"-e", cldrPluralJS}, langs...)...)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr

	if err := cmd.Run(); err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) && exit.ExitCode() == 2 {
			return nil, fmt.Errorf(
				"language %s is unknown to this Node's ICU, so its plural categories "+
					"cannot be derived — check the catalog filename, or use a Node build "+
					"with full ICU", stderr.String())
		}

		return nil, fmt.Errorf(
			"reading the CLDR plural categories for %v needs node on PATH — the gate "+
				"holds every catalog to the forms Intl.PluralRules can select, and it "+
				"asks Node rather than caching them so a wrong table cannot ratify "+
				"itself (`make lint` already needs node for eslint and vue-tsc): %w: %s",
			langs, err, stderr.String())
	}

	var forms pluralForms
	if err := json.Unmarshal(stdout.Bytes(), &forms); err != nil {
		return nil, fmt.Errorf("parse node plural output %q: %w", stdout.String(), err)
	}
	// Every language has at least "other", so an empty list means the bridge
	// broke — and an empty list is exactly what makes the per-language form
	// check silently demand nothing, so it must never be accepted quietly.
	for _, lang := range langs {
		if len(forms[lang]) == 0 {
			return nil, fmt.Errorf(
				"node reported no plural categories for %q — the CLDR bridge is "+
					"broken and the per-language form check would demand nothing", lang)
		}
	}

	return forms, nil
}
