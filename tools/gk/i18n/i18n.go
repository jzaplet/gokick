// Package i18n (the `gk i18n` subcommand) owns the single translation
// namespace in locale/messages.<lang>.json — ALL user-facing texts (UI labels
// and error messages alike) in frontend syntax ({param} placeholders, CLDR
// plural objects). The API ships {key, params} over the wire and the frontend
// renders every text, so the JSON catalogs are the one source of truth.
//
// The catalog FILENAMES are equally authoritative: they are the only place the
// supported-language set is declared by hand. Every other declaration of it is
// an artifact generated from them, so adding a language is a catalog file (plus
// a flag in the switcher) and `make i18n-gen` — never a hand edit in Go or TS:
//
//   - app/domain/shared/msgkey/keys.gen.go — one Go constant per key, so a
//     typo at an error call site is a compile error;
//   - app/domain/shared/lang_gen.go — the Lang constants, SupportedLangs and
//     ParseLang;
//   - assets/app-ui/I18n/langs.gen.ts — SUPPORTED_LANGS, the Lang union and
//     CANONICAL_LANG;
//   - assets/app-ui/I18n/catalog/<lang>.ts — the catalogs the t() renderer
//     consumes, and catalogs.gen.ts, the language→catalog record it looks up in.
//
// The CLDR plural categories each language can select are NOT cached: both
// `generate` and `check` read them out of Node's Intl.PluralRules, the same
// implementation the renderer selects forms with. A committed table would be
// byte-compared against itself and would ratify a wrong entry forever, so this
// one input is derived live — which is why `check` needs node on PATH.
//
// `gk i18n check` additionally gates catalog quality (key format, key + param
// + pluralness parity against the canonical catalog, valid CLDR forms, every
// category the language can select, lowercase-first params), artifact
// freshness, dead keys (unused in BOTH Go production code and frontend
// source), and Go and frontend call sites whose params miss a placeholder.
//
// Usage:
//
//	gk i18n generate   # (re)write every artifact above
//	gk i18n check      # verify artifacts match + run all gates; exit 1 on drift
